import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createApp } from '../apps/api/src/app';

// Issue #162: the previous version of this file was hand-maintained and silently went stale --
// 4 of its 6 entries were /api/developer/* routes removed months ago in the Developer Dashboard
// re-architecture, while real routes added since then (/api/imports/*, /api/approvals/*) were
// never added. Generating from the app's actual registered route table, rather than from
// buildOpenApiSpec (also considered, and also stale -- it only documents 12 of the app's routes
// and is missing /api/imports/* and /api/approvals/* itself), means this can't drift the same way
// again: every GET route Express actually has registered is included automatically.
//
// Scoped to GET routes with no path parameters, matching how zap-api-scan.sh actually uses this
// file -- each line becomes a single `zap-baseline.py -t <url>` spider+passive scan, which needs a
// real, directly-fetchable URL, not a route template like /api/reconciliation/:id. Routes needing
// a real resource id are a different, deliberately out-of-scope problem (would need seeded fixture
// data the scan could point at) -- not a regression from the old hand-written list, which had the
// same limitation.
type CliOptions = {
  outFile: string;
  checkOnly: boolean;
};

const defaultOutputPath = 'scripts/ops/zap-api-stage-targets.txt';

const usage = [
  'Usage: tsx scripts/generate-zap-api-targets.ts [--out scripts/ops/zap-api-stage-targets.txt] [--check]',
  '',
  'Examples:',
  '  tsx scripts/generate-zap-api-targets.ts',
  '  tsx scripts/generate-zap-api-targets.ts --check',
].join('\n');

const parseArgs = (argv: string[]): CliOptions => {
  const options: CliOptions = {
    outFile: defaultOutputPath,
    checkOnly: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];

    if (!token) {
      continue;
    }

    if (token === '--help' || token === '-h') {
      console.log(usage);
      process.exit(0);
    }

    if (token === '--check') {
      options.checkOnly = true;
      continue;
    }

    if (token === '--out') {
      const value = argv[index + 1];
      if (!value) {
        throw new Error('Missing value for --out');
      }
      options.outFile = value;
      index += 1;
      continue;
    }

    if (token.startsWith('--out=')) {
      const value = token.slice('--out='.length);
      if (!value) {
        throw new Error('Missing value for --out');
      }
      options.outFile = value;
      continue;
    }

    throw new Error(`Unknown argument: ${token}`);
  }

  return options;
};

type RouteLayer = {
  route?: {
    path: string | string[];
    methods: Record<string, boolean>;
  };
};

const discoverGetTargets = (): string[] => {
  const app = createApp();
  // Express 5 exposes this as `.router`; older Express (and @types/express) as `._router` --
  // support both rather than pinning to one, since the type declarations lag the runtime here.
  const router = (app as unknown as { router?: unknown; _router?: unknown }).router ??
    (app as unknown as { router?: unknown; _router?: unknown })._router;
  const stack = (router as { stack?: RouteLayer[] } | undefined)?.stack ?? [];

  const targets = new Set<string>();
  for (const layer of stack) {
    const route = layer.route;
    if (!route) {
      continue;
    }
    const path = Array.isArray(route.path) ? route.path[0] : route.path;
    if (!path || typeof path !== 'string') {
      continue;
    }
    if (path.includes(':')) {
      // Route template (e.g. /api/reconciliation/:id) -- not a directly-fetchable URL, and needs
      // real seeded fixture data to scan meaningfully. Out of scope here, same as the previous
      // hand-written list.
      continue;
    }
    if (!route.methods.get) {
      continue;
    }
    targets.add(path);
  }

  return [...targets].sort();
};

const renderTargets = (targets: string[]): string =>
  [
    '# Stage API OWASP ZAP baseline targets.',
    '# Entries can be absolute URLs or paths resolved against ZAP_API_BASE_URL.',
    '#',
    '# Generated by scripts/generate-zap-api-targets.ts from the app\'s own registered GET routes',
    '# (Issue #162) -- do not hand-edit. Regenerate with:',
    '#   npm run security:zap:targets:generate',
    '# Routes requiring a path parameter (e.g. /api/reconciliation/:id) are intentionally excluded',
    '# -- not a real URL until backed by a specific resource id.',
    '',
    ...targets,
    '',
  ].join('\n');

const run = async (): Promise<void> => {
  const options = parseArgs(process.argv.slice(2));
  const outputPath = resolve(process.cwd(), options.outFile);
  const targets = discoverGetTargets();
  const rendered = renderTargets(targets);

  if (options.checkOnly) {
    if (!existsSync(outputPath)) {
      throw new Error(`ZAP target list is missing: ${options.outFile}`);
    }

    const existing = readFileSync(outputPath, 'utf8');
    if (existing !== rendered) {
      throw new Error(
        `ZAP target list is out of date. Run: tsx scripts/generate-zap-api-targets.ts --out ${options.outFile}`,
      );
    }

    console.log(`ZAP target list is up to date: ${options.outFile} (${targets.length} targets)`);
    return;
  }

  writeFileSync(outputPath, rendered, 'utf8');
  console.log(`Wrote ${targets.length} ZAP targets to ${options.outFile}`);
};

run().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
